// Unit tests for ref links and referral webhook parsing (pure, no network).
import test from "node:test"
import assert from "node:assert/strict"
import {
  buildRefLink,
  extractReferral,
  findRefRule,
  isValidHandle,
  isValidRefCode,
  normalizeRefCode,
  sourceForRef,
  suggestRefCode,
} from "../lib/automations/referral.ts"
import { mergeContactSource } from "../lib/contacts/source.ts"

test("ref code validation: lowercase letters, digits, - and _, up to 64", () => {
  assert.equal(isValidRefCode("summer-sale_2"), true)
  assert.equal(isValidRefCode("Summer"), false) // uppercase not stored
  assert.equal(isValidRefCode("a b"), false)
  assert.equal(isValidRefCode("a=b"), false) // = is allowed by Meta but not generated by us
  assert.equal(isValidRefCode(""), false)
  assert.equal(isValidRefCode("x".repeat(65)), false)
  assert.equal(isValidRefCode(7), false)
  assert.equal(normalizeRefCode("  Promo-1 "), "promo-1")
})

test("suggestRefCode is valid and readable", () => {
  const code = suggestRefCode("Summer Sale!! 50% off", () => 0.5)
  assert.equal(isValidRefCode(code), true)
  assert.ok(code.startsWith("summer-sale-50-off-"))
  assert.equal(isValidRefCode(suggestRefCode("", () => 0.1)), true)
  assert.equal(isValidRefCode(suggestRefCode("नमस्ते", () => 0.1)), true)
})

test("buildRefLink uses ig.me/m/<handle>?ref=<code> and rejects bad input", () => {
  assert.equal(buildRefLink("my.brand_1", "promo-1"), "https://ig.me/m/my.brand_1?ref=promo-1")
  assert.equal(buildRefLink("@brand", "promo"), "https://ig.me/m/brand?ref=promo")
  assert.equal(buildRefLink(null, "promo"), null)
  assert.equal(buildRefLink("bad handle", "promo"), null)
  assert.equal(buildRefLink("brand", "Bad Code"), null)
  assert.equal(isValidHandle("a".repeat(31)), false)
})

test("extractReferral finds the object in message, postback and standalone events", () => {
  const ref = { ref: "promo-1", source: "SHORTLINKS", type: "OPEN_THREAD" }
  assert.deepEqual(extractReferral({ sender: { id: "u" }, message: { mid: "m", text: "hi", referral: ref } }), { ref: "promo-1", source: "SHORTLINKS", type: "OPEN_THREAD", via: "message" })
  assert.equal(extractReferral({ postback: { payload: "ICE_BREAKER_1", referral: ref } })?.via, "postback")
  assert.equal(extractReferral({ sender: { id: "u" }, timestamp: 1, referral: ref })?.via, "standalone")
  assert.equal(extractReferral({ message: { text: "hi" } }), null)
  assert.equal(extractReferral({ referral: { ref: "   " } }), null)
  assert.equal(extractReferral({ referral: { ref: 5 } }), null)
  assert.equal(extractReferral(null), null)
})

test("findRefRule: dm source + ref type only, case-insensitive", () => {
  const rules = [
    { id: "k", trigger_source: "dm", trigger_type: "keyword", trigger_value: "promo-1" },
    { id: "c", trigger_source: "comment", trigger_type: "ref", trigger_value: "promo-1" },
    { id: "r", trigger_source: "dm", trigger_type: "ref", trigger_value: "promo-1" },
  ]
  assert.equal(findRefRule(rules, "PROMO-1")?.id, "r")
  assert.equal(findRefRule(rules, "other"), null)
  assert.equal(findRefRule(rules, "  "), null)
})

test("mergeContactSource: first touch wins, never overwrites", () => {
  assert.deepEqual(mergeContactSource({}, "ref:promo-1"), { source: "ref:promo-1" })
  assert.deepEqual(mergeContactSource({ city: "Pune" }, "ref:a"), { city: "Pune", source: "ref:a" })
  assert.equal(mergeContactSource({ source: "ref:first" }, "ref:second"), null)
  assert.deepEqual(mergeContactSource({ source: "  " }, "ref:b"), { source: "ref:b" })
  assert.deepEqual(mergeContactSource(null, "ref:c"), { source: "ref:c" })
  assert.equal(mergeContactSource({}, "   "), null)
  assert.equal(sourceForRef(" Promo-1 "), "ref:promo-1")
})
